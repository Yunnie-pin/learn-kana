// Everyday conversation sentences: 100 imperative (perintah), 100 question
// (tanya) and 100 answer (jawaban) pairs the user practices in the Sentences
// mode. All sentences here are written with kana only (no kanji) so they
// become readable as soon as the kana groups are selected and cannot
// introduce a kanji that is not taught in kanaCharacters.js.
//
// Sentences are described with a template where a pair of braces marks the
// particles so their index is computed automatically:
//   'みず{を}のんでください' -> jp 'みずをのんでください', particles [2]
// A trailing question か is also treated as a particle, so
//   'これ{は}なんですか'     -> particles [2, 7]
// The 'pattern' of a sentence is picked up by sentencePattern in sentences.js
// from its ending: か becomes a question, ます a verb, others stay 'desu'.

// Every particle character that getReadableSentences can safely highlight in
// a sentence. Anything between braces must be one of these.
// `furigana` is an optional {index: reading} map for characters that are read
// differently than written, like the final は of こんにちは (read wa).
function s(tmpl, romaji, meaning, meaning_id, furigana) {
    const particles = [];
    let inParticle = false;
    let jp = '';
    for (const character of tmpl) {
        if (character === '{') { inParticle = true; continue; }
        if (character === '}') { inParticle = false; continue; }
        if (inParticle) particles.push(jp.length);
        jp += character;
    }
    // A sentence-final か is always the question particle
    if (jp.endsWith('か') && !particles.includes(jp.length - 1)) particles.push(jp.length - 1);
    particles.sort((a, b) => a - b);
    const sentence = { jp_character: jp, particles, romanji: [romaji], meaning, meaning_id };
    if (furigana) sentence.furigana = furigana;
    return sentence;
}

